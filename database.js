function postgresQuery(sql, params = []) {
  let index = 0;
  const statement = sql
    .replace(/name\s*=\s*\?\s+COLLATE\s+NOCASE/gi, "LOWER(name) = LOWER(?)")
    .replace(/\?/g, () => `$${++index}`)
    .replace(/\bLIKE\b/gi, "ILIKE")
    .replace(/\bCURRENT_TIMESTAMP\b/gi, "CURRENT_TIMESTAMP::TEXT")
    .replace(/COLLATE\s+NOCASE/gi, "");
  return { statement, params };
}

function createPostgresDatabase(databaseUrl) {
  const query = neon(databaseUrl);
  return {
    async exec(statement) {
      for (const command of statement.split(";").map((part) => part.trim()).filter(Boolean)) await query(command);
    },
    prepare(statement) {
      return {
        all: async (...params) => query(postgresQuery(statement, params).statement, params),
        get: async (...params) => (await query(postgresQuery(statement, params).statement, params))[0],
        run: async (...params) => {
          let runSql = postgresQuery(statement, params).statement;
          const returnsSerialId = /^\s*INSERT\s+INTO\s+(races|progeny|herd_members)\b/i.test(statement);
          if (returnsSerialId && !/\bRETURNING\b/i.test(runSql)) runSql += " RETURNING id";
          const result = await query(runSql, params, { fullResults: true });
          const rows = result.rows || [];
          return { changes: result.rowCount ?? rows.length, lastInsertRowid: rows[0]?.id };
        },
      };
    },
    rawQuery: (statement, params = []) => query(statement, params),
    async initialize() {
      for (const command of postgresSchema.split(";").map((part) => part.trim()).filter(Boolean)) await query(command);
      for (const command of [
        "ALTER TABLE herd_members ADD COLUMN IF NOT EXISTS color TEXT DEFAULT ''",
        "ALTER TABLE races ADD COLUMN IF NOT EXISTS notes TEXT DEFAULT ''",
        "ALTER TABLE races ADD COLUMN IF NOT EXISTS attachment_path TEXT DEFAULT ''",
        "ALTER TABLE races ADD COLUMN IF NOT EXISTS attachment_name TEXT DEFAULT ''",
      ]) await query(command);
    },
    kind: "postgres",
  };
}

async function createSqliteDatabase(databasePath) {
  const { default: Database } = await import("better-sqlite3");
  const sqlite = new Database(databasePath);
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");
  sqlite.exec(sqliteSchema);
  const herdMemberColumns = new Set(sqlite.prepare("PRAGMA table_info(herd_members)").all().map((column) => column.name));
  if (!herdMemberColumns.has("color")) sqlite.exec("ALTER TABLE herd_members ADD COLUMN color TEXT DEFAULT ''");
  const raceColumns = new Set(sqlite.prepare("PRAGMA table_info(races)").all().map((column) => column.name));
  for (const [column, definition] of [
    ["notes", "TEXT DEFAULT ''"], ["attachment_path", "TEXT DEFAULT ''"], ["attachment_name", "TEXT DEFAULT ''"],
  ]) {
    if (!raceColumns.has(column)) sqlite.exec(`ALTER TABLE races ADD COLUMN ${column} ${definition}`);
  }
  return {
    exec: async (statement) => sqlite.exec(statement),
    prepare: (statement) => {
      const prepared = sqlite.prepare(statement);
      return {
        all: async (...params) => prepared.all(...params),
        get: async (...params) => prepared.get(...params),
        run: async (...params) => prepared.run(...params),
      };
    },
    raw: sqlite,
    kind: "sqlite",
  };
}

export async function createDatabase(databasePath = path.resolve("data", "unaga.db")) {
  if (process.env.DATABASE_URL) {
    const database = createPostgresDatabase(process.env.DATABASE_URL);
    await database.initialize();
    return database;
  }
  return await createSqliteDatabase(databasePath);
}

export async function migrateSqliteToNeon(databasePath, databaseUrl = process.env.DATABASE_URL) {
  if (!databaseUrl) throw new Error("Set DATABASE_URL to the Neon connection string before migrating.");
  const { default: Database } = await import("better-sqlite3");
  const sqlite = new Database(databasePath, { readonly: true });
  try {
    const postgres = createPostgresDatabase(databaseUrl);
    await postgres.initialize();
    for (const table of ["horses", "users", "races", "progeny", "pedigrees", "herds", "herd_members"]) {
      const rows = sqlite.prepare(`SELECT * FROM ${table}`).all();
      if (!rows.length) continue;
      const columns = Object.keys(rows[0]);
      for (const row of rows) {
        const placeholders = columns.map((_, index) => `$${index + 1}`).join(", ");
        const names = columns.map((column) => `"${column}"`).join(", ");
        await postgres.rawQuery(
          `INSERT INTO ${table} (${names}) VALUES (${placeholders}) ON CONFLICT DO NOTHING`,
          columns.map((column) => row[column]),
        );
      }
      if (["users", "races", "progeny", "herd_members"].includes(table)) {
        await postgres.rawQuery(
          `SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE((SELECT MAX(id) FROM ${table}), 1), EXISTS (SELECT 1 FROM ${table}))`,
        );
      }
    }
  } finally {
    sqlite.close();
  }
}
